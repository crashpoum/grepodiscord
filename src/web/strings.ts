export function wt(lang: WebLang, key: WebKey, vars: Record<string, string | number> = {}): string {
  const s = WEB_STRINGS[lang]?.[key] ?? en[key];
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}
