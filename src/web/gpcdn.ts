/**
 * Official Grepolis unit/command icons, loaded at runtime from InnoGames' public image CDN and served same-origin
 * (so they also work inside the Discord Activity, whose proxy only reaches the mapped host, and the CSP stays 'self').
 * Nothing InnoGames-owned is stored in this repo: the bot fetches a fixed whitelist of images once, re-packs them into
 * two small sprites in memory (units as JPEG ≈55 KB instead of a 330 KB PNG; command types as one PNG strip) and serves
 * them with a long browser cache. If the CDN is unreachable the routes answer 503 and the client keeps its own SVG icons.
 */
import { createHash } from 'node:crypto';
import { config } from '../config.js';
import { log } from '../log.js';
import { GP_CMD_ICONS } from './cmdKind.js';

/** Version of the unit sprite: positions in web/src/icons.ts (GP_POS) belong to this exact file. */
export const GP_UNITS_VERSION = '66aaef2';
const UNITS_PATH = `/images/game/autogenerated/units/unit_icons_40x40_${GP_UNITS_VERSION}.png`;
/** Command-type icons (unit_overview/<name>.png), in the order of src/web/cmdKind.ts GP_CMD_ICONS. */
export const GP_CMD_FILES: readonly string[] = GP_CMD_ICONS;
const CMD_SIZE = 32;

export interface GpAsset { body: Buffer; type: string; etag: string; at: number }
export type GpName = 'units' | 'cmds';
const TTL = 7 * 24 * 3600_000;
const RETRY_AFTER_FAIL = 10 * 60_000;

type CanvasMod = typeof import('canvas');
let canvasMod: Promise<CanvasMod | null> | null = null;
const loadCanvas = () => (canvasMod ??= import('canvas').then((m) => (m.default ?? m) as CanvasMod).catch(() => null));

export class GpCdn {
  private cache = new Map<GpName, GpAsset>();
  private inflight = new Map<GpName, Promise<GpAsset | null>>();
  private failedAt = new Map<GpName, number>();
  constructor(private fetchImpl: typeof fetch = fetch, private now = Date.now, private base = config.grepolisCdn) {}

  async get(name: GpName): Promise<GpAsset | null> {
    if (!this.base) return null;
    const have = this.cache.get(name);
    if (have && this.now() - have.at < TTL) return have;
    if (this.now() - (this.failedAt.get(name) ?? -Infinity) < RETRY_AFTER_FAIL) return have ?? null;
    let p = this.inflight.get(name);
    if (!p) { p = this.load(name).finally(() => this.inflight.delete(name)); this.inflight.set(name, p); }
    return (await p) ?? have ?? null;
  }

  private async fetchPng(path: string): Promise<Buffer> {
    const res = await this.fetchImpl(`${this.base}${path}`, { signal: AbortSignal.timeout(20_000) });
    if (!res.ok) throw new Error(`HTTP ${res.status} for ${path}`);
    const b = Buffer.from(await res.arrayBuffer());
    if (b.length < 8 || b.readUInt32BE(0) !== 0x89504e47) throw new Error(`not a PNG: ${path}`);
    return b;
  }

  private async load(name: GpName): Promise<GpAsset | null> {
    try {
      const cv = await loadCanvas();
      let body: Buffer; let type: string;
      if (name === 'units') {
        const png = await this.fetchPng(UNITS_PATH);
        if (cv) {
          const img = await cv.loadImage(png);
          const c = cv.createCanvas(img.width, img.height); const x = c.getContext('2d');
          x.fillStyle = '#2b1d10'; x.fillRect(0, 0, img.width, img.height); x.drawImage(img, 0, 0);
          body = c.toBuffer('image/jpeg', { quality: 0.82 }); type = 'image/jpeg';
        } else { body = png; type = 'image/png'; }
      } else {
        if (!cv) throw new Error('canvas module unavailable');
        const pngs = await Promise.all(GP_CMD_FILES.map((f) => this.fetchPng(`/images/game/unit_overview/${f}.png`)));
        const c = cv.createCanvas(CMD_SIZE * pngs.length, CMD_SIZE); const x = c.getContext('2d');
        for (let i = 0; i < pngs.length; i++) x.drawImage(await cv.loadImage(pngs[i]), i * CMD_SIZE, 0, CMD_SIZE, CMD_SIZE);
        body = c.toBuffer('image/png'); type = 'image/png';
      }
      const a: GpAsset = { body, type, at: this.now(), etag: `"g${createHash('sha1').update(body).digest('base64url').slice(0, 16)}"` };
      this.cache.set(name, a);
      log.info(`web: official Grepolis ${name} icons cached (${body.length} B ${type})`);
      return a;
    } catch (e) {
      this.failedAt.set(name, this.now());
      log.warn(`web: official Grepolis ${name} icons unavailable, clients use the built-in icons: ${(e as Error).message}`);
      return null;
    }
  }
}
