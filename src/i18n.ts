export const STRINGS: Record<Lang, Record<Key, string>> = { en, el };
export type StringKey = Key;

export function t(lang: Lang, key: Key, vars: Record<string, string | number> = {}): string {
  const s = STRINGS[lang]?.[key] ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

export function fmt(n: number, lang: Lang): string {
  return n.toLocaleString(lang === 'el' ? 'el-GR' : 'en-GB');
}
